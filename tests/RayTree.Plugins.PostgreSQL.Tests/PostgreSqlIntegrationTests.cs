using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using DotNet.Testcontainers.Containers;
using Npgsql;
using RayTree.Core.Models;
using RayTree.Core.Tracking;
using RayTree.Plugins.PostgreSQL.Outbox;

namespace RayTree.Plugins.PostgreSQL.Tests;

public class TestEntity
{
    public int Id { get; set; }
}

[NonParallelizable]
public class PostgreSqlOutboxIntegrationTests : IAsyncDisposable
{
    private readonly IContainer _postgres = PostgresContainerFactory.Create();
    private PostgreSqlOutbox<TestEntity> _outbox = null!;

    [OneTimeSetUp]
    public async Task OneTimeSetUp()
    {
        await _postgres.StartAsync();
    }

    [SetUp]
    public async Task SetUp()
    {
        _outbox = new PostgreSqlOutbox<TestEntity>(new PostgreSqlOutboxOptions
        {
            ConnectionString = _postgres.GetConnectionString(),
            OutboxTableName  = "test_entity_outbox"
        });
        await _outbox.InitializeAsync();
    }

    public ValueTask DisposeAsync() => _postgres.DisposeAsync();

    [TearDown]
    public async Task TearDown()
    {
        await using var conn = new NpgsqlConnection(_postgres.GetConnectionString());
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand("TRUNCATE test_entity_outbox RESTART IDENTITY", conn);
        await cmd.ExecuteNonQueryAsync();
    }

    [Test]
    public async Task WriteAsync_InsertsChange_WithAutoGeneratedId()
    {
        var change = CreateTestChange();

        await _outbox.WriteAsync(change);

        Assert.That(change.Id, Is.GreaterThan(0));
        var stored = await _outbox.GetByIdAsync<TestEntity>(change.Id);
        Assert.That(stored, Is.Not.Null);
        Assert.That(stored!.EntityId, Is.EqualTo(change.EntityId));
        Assert.That(stored.ChangeType, Is.EqualTo(ChangeType.Insert));
    }

    [Test]
    public async Task GetUnpublishedAsync_ReturnsUnpublishedChanges()
    {
        await _outbox.WriteAsync(CreateTestChange());
        await _outbox.WriteAsync(CreateTestChange());

        var unpublished = await _outbox.GetUnpublishedAsync<TestEntity>(10);
        Assert.That(unpublished, Has.Count.EqualTo(2));
    }

    [Test]
    public async Task MarkPublishedAsync_MarksChangeAsPublished()
    {
        var change = CreateTestChange();

        await _outbox.WriteAsync(change);
        await _outbox.MarkPublishedAsync(change.Id);

        var unpublished = await _outbox.GetUnpublishedAsync<TestEntity>(10);
        Assert.That(unpublished, Is.Empty);
    }

    [Test]
    public async Task GetUnpublishedAsync_WithChangeTypeFilter_ReturnsMatchingChanges()
    {
        await _outbox.WriteAsync(CreateTestChange(changeType: ChangeType.Insert));
        await _outbox.WriteAsync(CreateTestChange(changeType: ChangeType.Delete));

        var filtered = await _outbox.GetUnpublishedAsync<TestEntity>(changeType: ChangeType.Insert, batchSize: 10);
        Assert.That(filtered, Has.Count.EqualTo(1));
        Assert.That(filtered[0].ChangeType, Is.EqualTo(ChangeType.Insert));
    }

    [Test]
    public async Task GetUnpublishedAsync_WithSinceFilter_ReturnsMatchingChanges()
    {
        await _outbox.WriteAsync(CreateTestChange(timestamp: DateTime.UtcNow.AddHours(-2)));
        await _outbox.WriteAsync(CreateTestChange(timestamp: DateTime.UtcNow));

        var filtered = await _outbox.GetUnpublishedAsync<TestEntity>(since: DateTime.UtcNow.AddMinutes(-30), batchSize: 10);
        Assert.That(filtered, Has.Count.EqualTo(1));
    }

    [Test]
    public async Task GetByIdAsync_WithNonExistentId_ReturnsNull()
    {
        var result = await _outbox.GetByIdAsync<TestEntity>(999);
        Assert.That(result, Is.Null);
    }

    [Test]
    public async Task CleanupPublishedAsync_RemovesOldPublishedChanges()
    {
        var oldChange = CreateTestChange(timestamp: DateTime.UtcNow.AddHours(-3));
        var newChange = CreateTestChange(timestamp: DateTime.UtcNow);

        await _outbox.WriteAsync(oldChange);
        await _outbox.WriteAsync(newChange);
        await _outbox.MarkPublishedAsync(oldChange.Id);

        var deleted = await _outbox.CleanupPublishedAsync(TimeSpan.FromHours(1));
        Assert.That(deleted, Is.EqualTo(1));
    }

    [Test]
    public async Task CleanupPublishedAsync_DeletesInBatches()
    {
        for (var i = 0; i < 5; i++)
        {
            var change = CreateTestChange(timestamp: DateTime.UtcNow.AddHours(-3));
            await _outbox.WriteAsync(change);
            await _outbox.MarkPublishedAsync(change.Id);
        }

        var outboxWithSmallBatch = new PostgreSqlOutbox<TestEntity>(new PostgreSqlOutboxOptions
        {
            ConnectionString = _postgres.GetConnectionString(),
            OutboxTableName  = "test_entity_outbox",
            CleanupBatchSize = 2
        });

        var deleted = await outboxWithSmallBatch.CleanupPublishedAsync(TimeSpan.FromHours(1));
        Assert.That(deleted, Is.EqualTo(5));
    }

    [Test]
    public async Task CleanupStaleUnpublishedAsync_RemovesOldUnpublishedChanges()
    {
        var staleChange  = CreateTestChange(timestamp: DateTime.UtcNow.AddDays(-31));
        var recentChange = CreateTestChange(timestamp: DateTime.UtcNow);

        await _outbox.WriteAsync(staleChange);
        await _outbox.WriteAsync(recentChange);

        var deleted = await _outbox.CleanupStaleUnpublishedAsync(TimeSpan.FromDays(30));
        Assert.That(deleted, Is.EqualTo(1));

        var remaining = await _outbox.GetUnpublishedAsync<TestEntity>(10);
        Assert.That(remaining, Has.Count.EqualTo(1));
        Assert.That(remaining[0].Id, Is.EqualTo(recentChange.Id));
    }

    [Test]
    public async Task CleanupStaleUnpublishedAsync_DoesNotRemovePublishedChanges()
    {
        var oldPublished = CreateTestChange(timestamp: DateTime.UtcNow.AddDays(-31));
        await _outbox.WriteAsync(oldPublished);
        await _outbox.MarkPublishedAsync(oldPublished.Id);

        var deleted = await _outbox.CleanupStaleUnpublishedAsync(TimeSpan.FromDays(30));
        Assert.That(deleted, Is.EqualTo(0));
    }

    [Test]
    public async Task WriteAsync_StoresCorrelationId()
    {
        var correlationId = Guid.NewGuid();
        var change = CreateTestChange();
        change.CorrelationId = correlationId;

        await _outbox.WriteAsync(change);
        var stored = await _outbox.GetByIdAsync<TestEntity>(change.Id);
        Assert.That(stored!.CorrelationId, Is.EqualTo(correlationId));
    }

    [Test]
    public async Task WriteAsync_WithState_RoundTripsEntityData()
    {
        var change = new EntityChange<TestEntity>
        {
            EntityType = typeof(TestEntity).FullName!,
            EntityId   = "42",
            ChangeType = ChangeType.Insert,
            State      = new TestEntity { Id = 42 }
        };

        await _outbox.WriteAsync(change);
        var stored = await _outbox.GetByIdAsync<TestEntity>(change.Id);

        Assert.That(stored!.State, Is.Not.Null);
        Assert.That(stored.State!.Id, Is.EqualTo(42));
    }

    private static EntityChange<TestEntity> CreateTestChange(
        ChangeType changeType = ChangeType.Insert,
        DateTime? timestamp = null) => new()
    {
        EntityType = typeof(TestEntity).FullName!,
        EntityId   = Guid.NewGuid().ToString(),
        ChangeType = changeType,
        Timestamp  = timestamp ?? DateTime.UtcNow,
        CorrelationId = Guid.NewGuid(),
        State      = new TestEntity { Id = 1 }
    };
}

[Table("test_users")]
